/**
 * Maker import engine — legacy skill migration with lossless architecture.
 *
 * Migrates a legacy OC skill by adding a `.claws/` governance directory
 * alongside the original files. Per the lossless architecture principle,
 * the import command NEVER modifies original files — it is strictly add-only.
 *
 * The `.claws/` directory contains:
 * - governance.yaml — governance annotations from annotate analysis
 * - manifest.yaml — file inventory and compilation metadata
 * - decorators.ts — suggested decorator stubs for handler propagation
 *
 * @module claws-sdk/maker/import
 */

import { mkdir, writeFile, readFile, readdir } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

import { pathExists } from '../util/fs.js';
import { makerAnnotate } from './annotate.js';
import type { MakerAnnotateResult } from './annotate.js';
import type { GovernanceTier } from './types.js';

// ── Types ──────────────────────────────────────────────────────────────

/**
 * Options for the import operation.
 */
export interface MakerImportOptions {
  /** Path to the legacy skill directory. */
  readonly skillDir: string;
  /** Override governance tier (default: inferred from workspace state). */
  readonly tierOverride?: GovernanceTier | undefined;
}

/**
 * A file entry in the import manifest.
 */
export interface ImportManifestEntry {
  /** Relative path within the skill directory. */
  readonly path: string;
  /** SHA-256 hash of the file content at import time. */
  readonly hash: string;
  /** File role. */
  readonly role: 'skill-md' | 'handler' | 'config' | 'other';
}

/**
 * Result of the import operation.
 */
export interface MakerImportResult {
  /** Skill name. */
  readonly name: string;
  /** Path to the created .claws/ directory. */
  readonly clawsDir: string;
  /** Files created in .claws/ (relative to skill dir). */
  readonly createdFiles: readonly string[];
  /** Original files that were NOT modified (lossless verification). */
  readonly originalFiles: readonly string[];
  /** Manifest entries for all original files. */
  readonly manifest: readonly ImportManifestEntry[];
  /** Annotate result used for governance generation. */
  readonly annotateResult: MakerAnnotateResult;
  /** Governance tier applied. */
  readonly tier: GovernanceTier;
  /** Duration in milliseconds. */
  readonly durationMs: number;
}

// ── Utilities ─────────────────────────────────────────────────────────

/**
 * Compute SHA-256 hash of a string.
 */
function sha256(content: string): string {
  return createHash('sha256').update(content, 'utf-8').digest('hex');
}


/**
 * Determine file role from its filename.
 */
function classifyFileRole(filename: string): ImportManifestEntry['role'] {
  const lower = filename.toLowerCase();
  if (lower === 'skill.md') return 'skill-md';
  if (lower === 'handler.ts' || lower === 'handler.js') return 'handler';
  if (lower.endsWith('.json') || lower.endsWith('.yaml') || lower.endsWith('.yml')) return 'config';
  return 'other';
}

// ── Governance YAML Generation ────────────────────────────────────────

/**
 * Build governance.yaml content from annotate results.
 */
function buildGovernanceYaml(result: MakerAnnotateResult, tier: GovernanceTier): string {
  const lines: string[] = [
    '# claws governance — auto-generated by `claws maker import`',
    '# Do not edit manually. Re-run `claws maker annotate` to refresh.',
    '',
    `name: ${result.name}`,
    `tier: ${tier}`,
    `risk: R${result.inferredRisk}`,
  ];

  if (result.oboFindings.length > 0) {
    lines.push('obo: true');
    lines.push('obo_capabilities:');
    for (const finding of result.oboFindings) {
      lines.push(`  - type: ${finding.type}`);
      lines.push(`    pattern: ${finding.pattern}`);
      lines.push(`    confidence: ${finding.confidence.toFixed(2)}`);
    }
  } else {
    lines.push('obo: false');
  }

  if (result.dataLabels.length > 0) {
    lines.push('data_labels:');
    for (const dl of result.dataLabels) {
      lines.push(`  - label: ${dl.label}`);
      lines.push(`    reason: "${dl.reason}"`);
      lines.push(`    confidence: ${dl.confidence.toFixed(2)}`);
    }
  }

  lines.push('');
  return lines.join('\n');
}

/**
 * Build manifest.yaml content from file inventory.
 */
function buildManifestYaml(
  name: string,
  entries: readonly ImportManifestEntry[],
): string {
  const lines: string[] = [
    '# claws manifest — auto-generated by `claws maker import`',
    '# Records original file state at import time for drift detection.',
    '',
    `skill: ${name}`,
    `imported_at: ${new Date().toISOString()}`,
    'files:',
  ];

  for (const entry of entries) {
    lines.push(`  - path: ${entry.path}`);
    lines.push(`    role: ${entry.role}`);
    lines.push(`    hash: ${entry.hash}`);
  }

  lines.push('');
  return lines.join('\n');
}

/**
 * Build decorators.ts stub with suggested decorators.
 */
function buildDecoratorsStub(result: MakerAnnotateResult): string {
  const lines: string[] = [
    '/**',
    ' * Suggested governance decorators for handler.ts.',
    ' * Auto-generated by `claws maker import`.',
    ' *',
    ' * Copy these decorators to your handler.ts to enable governance tracking.',
    ' * Re-run `claws maker annotate` to refresh suggestions.',
    ' */',
    '',
  ];

  for (const dec of result.decorators) {
    if (dec.args) {
      lines.push(`// ${dec.decorator}(${dec.args})`);
    } else {
      lines.push(`// ${dec.decorator}()`);
    }
  }

  lines.push('');
  return lines.join('\n');
}

// ── Core Engine ───────────────────────────────────────────────────────

/**
 * Run the maker import pipeline on a legacy skill directory.
 *
 * Lossless architecture: original files are NEVER modified. The `.claws/`
 * directory is created alongside originals with governance metadata.
 *
 * @param options - Import options with skill directory path
 * @returns MakerImportResult with created files and manifest
 * @throws Error if skill directory does not exist
 * @throws Error if .claws/ directory already exists (already imported)
 */
export async function makerImport(
  options: MakerImportOptions,
): Promise<MakerImportResult> {
  const start = performance.now();

  // Verify skill directory exists
  if (!(await pathExists(options.skillDir))) {
    throw new Error(`Skill directory does not exist: ${options.skillDir}`);
  }

  // Verify .claws/ does not already exist
  const clawsDir = join(options.skillDir, '.claws');
  if (await pathExists(clawsDir)) {
    throw new Error(`Skill already imported: .claws/ directory exists at ${clawsDir}`);
  }

  // Run annotate analysis
  const annotateResult = await makerAnnotate({ skillDir: options.skillDir });

  // Determine tier
  const tier = options.tierOverride ?? annotateResult.suggestedTier;

  // Inventory original files
  const entries = await readdir(options.skillDir);
  const originalFiles: string[] = [];
  const manifest: ImportManifestEntry[] = [];

  for (const entry of entries) {
    const filePath = join(options.skillDir, entry);
    let content: string;
    try {
      content = await readFile(filePath, 'utf-8');
    } catch {
      // Skip directories and binary files
      continue;
    }

    originalFiles.push(entry);
    manifest.push({
      path: entry,
      hash: sha256(content),
      role: classifyFileRole(entry),
    });
  }

  // Create .claws/ directory
  await mkdir(clawsDir, { recursive: true });

  // Write governance files — add-only, never touch originals
  const createdFiles: string[] = [];

  const governanceContent = buildGovernanceYaml(annotateResult, tier);
  await writeFile(join(clawsDir, 'governance.yaml'), governanceContent, 'utf-8');
  createdFiles.push('.claws/governance.yaml');

  const manifestContent = buildManifestYaml(annotateResult.name, manifest);
  await writeFile(join(clawsDir, 'manifest.yaml'), manifestContent, 'utf-8');
  createdFiles.push('.claws/manifest.yaml');

  const decoratorsContent = buildDecoratorsStub(annotateResult);
  await writeFile(join(clawsDir, 'decorators.ts'), decoratorsContent, 'utf-8');
  createdFiles.push('.claws/decorators.ts');

  const durationMs = performance.now() - start;

  return {
    name: annotateResult.name,
    clawsDir,
    createdFiles,
    originalFiles,
    manifest,
    annotateResult,
    tier,
    durationMs,
  };
}
