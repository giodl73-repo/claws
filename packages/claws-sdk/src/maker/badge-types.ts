/**
 * Badge metadata types — BadgeMetadata, BadgeQualifier, BadgeStaleness,
 * BadgePolicy for the badge generation pipeline.
 *
 * Badge generation lives in claws-sdk (the `claws` namespace).
 * Badge rendering for ClawHub display is a separate `clawhub` concern.
 *
 * @module claws-sdk/maker/badge-types
 */

import type { GovernanceTier, RiskLevel } from './types.js';
import type { SignatureStatus } from './manifest.js';

// ── Badge Qualifier ─────────────────────────────────────────────────

/**
 * Tier-aware badge qualifier.
 *
 * - DECLARED → "self-reported" — attestation, not verification
 * - TYPED → no qualifier — decorators present, type-checked
 * - VERIFIED → "verified" — fully compiled, all governance checks passing
 */
export type BadgeQualifier = 'self-reported' | 'verified' | null;

// ── Badge Staleness ─────────────────────────────────────────────────

/**
 * Badge staleness state.
 *
 * - current: badge reflects the latest governance metadata
 * - stale: governance metadata has changed since badge generation
 * - unknown: badge age cannot be determined
 */
export type BadgeStaleness = 'current' | 'stale' | 'unknown';

// ── Badge Inconsistency ─────────────────────────────────────────────

/**
 * A governance metadata inconsistency detected during badge generation.
 */
export interface BadgeInconsistency {
  /** Machine-readable inconsistency code. */
  readonly code: string;
  /** Human-readable description. */
  readonly message: string;
  /** Severity of the inconsistency. */
  readonly severity: 'warning' | 'error';
}

// ── Badge Policy ────────────────────────────────────────────────────

/**
 * Fleet-level badge policy — minimum requirements for badge display.
 */
export interface BadgePolicy {
  /** Minimum tier for badge display. */
  readonly minimumTier: GovernanceTier;
  /** Whether signing is required for badge display. */
  readonly requireSigned: boolean;
  /** Whether inconsistencies block badge generation. */
  readonly blockOnInconsistency: boolean;
}

// ── Supply Chain Badge ──────────────────────────────────────────────

/**
 * Supply chain badge — independent of governance tier.
 *
 * Indicates whether the published artifact has build provenance
 * (cryptographic attestation of build origin).
 */
export interface SupplyChainBadge {
  /** Whether the manifest is signed. */
  readonly signed: boolean;
  /** Signature status from the manifest. */
  readonly signatureStatus: SignatureStatus;
}

// ── Badge Metadata ──────────────────────────────────────────────────

/**
 * Complete badge metadata for a skill.
 *
 * Generated by the badge pipeline in claws-sdk. Consumed by
 * the clawhub rendering layer (not this module's concern).
 */
export interface BadgeMetadata {
  /** Governance tier. */
  readonly tier: GovernanceTier;
  /** Tier-aware qualifier (null for TYPED). */
  readonly qualifier: BadgeQualifier;
  /** Risk level (1-5). */
  readonly risk: RiskLevel;
  /** Whether OBO governance is enabled. */
  readonly obo: boolean;
  /** OBO scope description. */
  readonly oboScope: string;
  /** Data classification labels. */
  readonly dataLabels: readonly string[];
  /** Supply chain badge (independent of tier). */
  readonly supplyChain: SupplyChainBadge;
  /** Badge staleness state. */
  readonly staleness: BadgeStaleness;
  /** Detected governance inconsistencies. */
  readonly inconsistencies: readonly BadgeInconsistency[];
  /** Badge generation timestamp (ISO 8601). */
  readonly generatedAt: string;
}

/**
 * Pre-badge sentinel — indicates a skill has not been through
 * the badge pipeline. Absence of badge, not error badge.
 */
export type PreBadge = null;
