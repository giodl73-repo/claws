/**
 * Claude Code emitter templates.
 *
 * Pure string-formatting helpers -- no I/O, no side effects. Separates
 * output formatting from emit orchestration so the formatter can be
 * unit-tested and changed without touching disk or the guard pipeline.
 *
 * @module claws-sdk/compiler/emit/cc-templates
 */

import type {
  SoulIR,
  ToolsIR,
  AgentsIR,
  SkillsIR,
  IdentityIR,
  SkillMetadataIR,
  ToolDeclarationIR,
} from '../ir/workspace-ir.js';

/**
 * Permission-tier derived from trust level. Higher trust tools are listed
 * as allow-by-default; lower trust surfaces as require-approval.
 */
export type CCPermission = 'allow' | 'ask' | 'deny';

/**
 * Map TrustLevel (0..4) to a Claude Code permission tier.
 *
 *  0-1  → allow (low-risk, auto-granted)
 *  2-3  → ask   (medium-risk, prompt before run)
 *  4+   → deny  (high-risk, never auto-granted)
 *  <0   → deny  (unknown trust, refuse)
 */
export function trustToPermission(trustLevel: number): CCPermission {
  if (trustLevel < 0) return 'deny';
  if (trustLevel <= 1) return 'allow';
  if (trustLevel <= 3) return 'ask';
  return 'deny';
}

/**
 * Escape a string for safe embedding inside a markdown bullet line. Only
 * control characters matter -- backticks and angle brackets are content
 * in markdown and pass through untouched.
 */
function mdSafe(text: string): string {
  return text.replace(/[\r\n]+/g, ' ').trim();
}

/**
 * Format CLAUDE.md from SoulIR + ToolsIR + AgentsIR.
 *
 * Sections (in order):
 *   1. Marker line (formatter-resistant single-line comment)
 *   2. Persona (from SoulIR.persona)
 *   3. Principles (bulleted, from SoulIR.principles)
 *   4. Voice (optional paragraph, from SoulIR.voice)
 *   5. Tools (table of tool -> permission tier)
 *   6. Agents (delegation graph summary)
 *   7. Boundaries (bulleted, from SoulIR.boundaries)
 */
export function formatClaudeMd(
  soul: SoulIR,
  tools: ToolsIR,
  agents: AgentsIR,
  compilerVersion: string,
): string {
  const lines: string[] = [];

  lines.push(`<!-- claws-governance:claude-code:v${compilerVersion} -->`);
  lines.push('');
  lines.push('# Project Instructions');
  lines.push('');
  lines.push(
    `> Generated by claws v${compilerVersion}. DO NOT EDIT — regenerate from OC workspace.`,
  );
  lines.push('');

  // Persona
  lines.push('## Persona');
  lines.push('');
  lines.push(soul.persona.length > 0 ? soul.persona : '_No persona declared._');
  lines.push('');

  // Principles
  lines.push('## Principles');
  lines.push('');
  if (soul.principles.length === 0) {
    lines.push('_No principles declared._');
  } else {
    for (const p of soul.principles) {
      lines.push(`- ${mdSafe(p)}`);
    }
  }
  lines.push('');

  // Voice (optional)
  if (soul.voice !== undefined && soul.voice.length > 0) {
    lines.push('## Voice');
    lines.push('');
    lines.push(mdSafe(soul.voice));
    lines.push('');
  }

  // Tools
  lines.push('## Tools');
  lines.push('');
  if (tools.tools.length === 0) {
    lines.push('_No tools declared._');
  } else {
    lines.push('| Tool | Trust | Permission |');
    lines.push('| --- | --- | --- |');
    const sorted = [...tools.tools].sort((a, b) => a.name.localeCompare(b.name));
    for (const t of sorted) {
      const perm = trustToPermission(t.trustLevel);
      lines.push(`| \`${t.name}\` | T${t.trustLevel} | ${perm} |`);
    }
  }
  lines.push('');

  // Agents / delegation
  lines.push('## Agents');
  lines.push('');
  if (agents.agents.length === 0) {
    lines.push('_No agents declared._');
  } else {
    const sortedAgents = [...agents.agents].sort((a, b) => a.name.localeCompare(b.name));
    for (const a of sortedAgents) {
      lines.push(`- **${a.name}** — ${mdSafe(a.description)}`);
    }
    if (agents.delegations.length > 0) {
      lines.push('');
      lines.push('### Delegation');
      lines.push('');
      const sortedDelegs = [...agents.delegations].sort((x, y) => {
        const c = x.from.localeCompare(y.from);
        return c !== 0 ? c : x.to.localeCompare(y.to);
      });
      for (const d of sortedDelegs) {
        lines.push(`- \`${d.from}\` → \`${d.to}\``);
      }
    }
  }
  lines.push('');

  // Boundaries
  lines.push('## Boundaries');
  lines.push('');
  if (soul.boundaries.length === 0) {
    lines.push('_No boundaries declared._');
  } else {
    for (const b of soul.boundaries) {
      lines.push(`- ${mdSafe(b.text)}`);
    }
  }
  lines.push('');

  return lines.join('\n');
}

// ── settings.json ─────────────────────────────────────────────────────

/**
 * Claude Code settings.json shape. Only the subset claws writes is modelled.
 */
export interface CCSettings {
  readonly $schema?: string;
  readonly permissions: {
    readonly allow: readonly string[];
    readonly ask: readonly string[];
    readonly deny: readonly string[];
  };
  readonly env: Readonly<Record<string, string>>;
  readonly claws: {
    readonly version: string;
    readonly organization: string;
    readonly team: string;
  };
}

/**
 * Build the settings.json content from ToolsIR + IdentityIR.
 *
 * Permission buckets are derived from tool trust levels via
 * `trustToPermission`. OBO tools always land in `ask` regardless of
 * their underlying trust level — they require user elicitation.
 */
export function formatSettingsJson(
  tools: ToolsIR,
  identity: IdentityIR,
  compilerVersion: string,
): string {
  const allow: string[] = [];
  const ask: string[] = [];
  const deny: string[] = [];

  for (const tool of [...tools.tools].sort((a, b) => a.name.localeCompare(b.name))) {
    const bucket = resolveBucket(tool);
    if (bucket === 'allow') allow.push(tool.name);
    else if (bucket === 'ask') ask.push(tool.name);
    else deny.push(tool.name);
  }

  const settings: CCSettings = {
    permissions: { allow, ask, deny },
    env: {},
    claws: {
      version: compilerVersion,
      organization: identity.organization,
      team: identity.team,
    },
  };

  return `${JSON.stringify(settings, null, 2)}\n`;
}

/**
 * Bucket resolution: OBO tools always require elicitation → ask bucket.
 * Non-OBO tools map via trust level.
 */
function resolveBucket(tool: ToolDeclarationIR): CCPermission {
  if (tool.oboFlag) return 'ask';
  return trustToPermission(tool.trustLevel);
}

// ── Command stubs ─────────────────────────────────────────────────────

/**
 * Format a single skill as a Claude Code slash-command markdown stub.
 *
 * Returns a markdown file body. The caller chooses the file path
 * (`.claude/commands/{slug}.md`).
 */
export function formatCommandStub(skill: SkillMetadataIR, compilerVersion: string): string {
  const lines: string[] = [];
  lines.push(`<!-- claws-governance:claude-code:v${compilerVersion} -->`);
  lines.push(`# /${skill.name}`);
  lines.push('');
  lines.push(mdSafe(skill.description));
  lines.push('');
  if (skill.requiredTools.length > 0) {
    lines.push('## Required Tools');
    lines.push('');
    for (const t of [...skill.requiredTools].sort()) {
      lines.push(`- \`${t}\``);
    }
    lines.push('');
  }
  lines.push('## Source');
  lines.push('');
  lines.push(`\`${skill.path}\``);
  lines.push('');
  return lines.join('\n');
}

/**
 * Produce a filename-safe slug for a skill name.
 *
 * Used to compute the `.claude/commands/{slug}.md` path. Empty or
 * all-punctuation names collapse to "skill" to guarantee a valid path.
 */
export function slugifySkillName(name: string): string {
  let slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  let start = 0;
  while (start < slug.length && slug.charCodeAt(start) === 45) start += 1;
  let end = slug.length;
  while (end > start && slug.charCodeAt(end - 1) === 45) end -= 1;
  slug = slug.slice(start, end);
  return slug.length > 0 ? slug : 'skill';
}

/**
 * Enumerate every skill stub pair: (relative path, content).
 */
export function formatSkillStubs(
  skills: SkillsIR,
  compilerVersion: string,
): ReadonlyArray<readonly [string, string]> {
  const out: Array<readonly [string, string]> = [];
  const seen = new Set<string>();
  for (const skill of [...skills.skills].sort((a, b) => a.name.localeCompare(b.name))) {
    let slug = slugifySkillName(skill.name);
    // Disambiguate collisions so two skills with equivalent slugs both land.
    if (seen.has(slug)) {
      let i = 2;
      while (seen.has(`${slug}-${i}`)) i += 1;
      slug = `${slug}-${i}`;
    }
    seen.add(slug);
    const path = `.claude/commands/${slug}.md`;
    out.push([path, formatCommandStub(skill, compilerVersion)] as const);
  }
  return out;
}
