#!/usr/bin/env node
// Generate src/ast/grammars.generated.ts.
//
// Sources:
//   1. The 11 openclaw-*.peg files under design/astro/grammars/. Each is
//      embedded verbatim so the package ships without filesystem reads
//      at runtime.
//   2. A hand-maintained `bootstrap` stub for BOOTSTRAP.md, which has no
//      Tier-3 PEG grammar today (freeform onboarding prose). The stub
//      lives in this script so regeneration preserves it.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '../../../..');
const grammarsDir = join(repoRoot, 'design/astro/grammars');

const PEG_KINDS = [
  'agents',
  'config',
  'entities',
  'governance',
  'memory',
  'roles',
  'skills',
  'soul',
  'tasks',
  'tools',
  'workflows',
];

/**
 * Hand-maintained stubs for kinds without a Tier-3 PEG grammar. Survives
 * regeneration because it lives here, not in the .peg directory.
 */
const STUB_KINDS = {
  bootstrap: `# openclaw-bootstrap.stub — Freeform onboarding prose (BOOTSTRAP.md)
#
# NOTE: BOOTSTRAP.md has no Tier-3 PEG grammar. It is loaded verbatim by
# upstream loadWorkspaceBootstrapFiles (agents/workspace.ts:602-667) and
# concatenated into the agent's bootstrap context. This stub exists so
# the kind round-trips through parse/emit; structural validation is
# intentionally absent.
#
# Top-level: any sequence of bytes (UTF-8 text). Parser falls back to
# BaseAst (frontmatter + preamble + ## heading blocks) for editor outline.

OCBootstrap     <- .*
`,
};

const ALL_KINDS = [...PEG_KINDS, ...Object.keys(STUB_KINDS)].sort();

const files = readdirSync(grammarsDir)
  .filter((f) => PEG_KINDS.includes(f.replace(/^openclaw-/, '').replace(/\.peg$/, '')))
  .sort();

if (files.length !== PEG_KINDS.length) {
  console.error(
    `Expected ${PEG_KINDS.length} openclaw-*.peg files, found ${files.length}`,
  );
  process.exit(1);
}

const header = `// PARTIALLY-GENERATED — the ${PEG_KINDS.length} openclaw-*.peg grammar strings below are
// regenerated by \`node scripts/generate-grammars.mjs\` from
// design/astro/grammars/openclaw-*.peg.
//
// Stub kinds (currently: \`bootstrap\`) are hand-maintained inside the
// generator script and survive regeneration.

`;

const parts = [header];
parts.push(`export type WorkspaceFileKind =\n`);
parts.push(ALL_KINDS.map((k) => `  | '${k}'`).join('\n'));
parts.push(';\n\n');
parts.push(`export const WORKSPACE_FILE_KINDS: readonly WorkspaceFileKind[] = [\n`);
for (const k of ALL_KINDS) parts.push(`  '${k}',\n`);
parts.push(`] as const;\n\n`);
parts.push(`export const grammars: Record<WorkspaceFileKind, string> = {\n`);

for (const kind of ALL_KINDS) {
  let content;
  if (PEG_KINDS.includes(kind)) {
    const file = `openclaw-${kind}.peg`;
    content = readFileSync(join(grammarsDir, file), 'utf8');
  } else {
    content = STUB_KINDS[kind];
  }
  const escaped = content
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
  parts.push(`  ${kind}: \`${escaped}\`,\n`);
}

parts.push(`};\n`);

const outPath = join(here, '..', 'src/ast/grammars.generated.ts');
writeFileSync(outPath, parts.join(''), 'utf8');
console.log(`Wrote ${outPath}`);
